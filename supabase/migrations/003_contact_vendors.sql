-- Run this in Supabase SQL Editor
-- Creates the contact_vendors directory used by the Contact Vendors page.
CREATE TABLE IF NOT EXISTS public.contact_vendors (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  google_place_id text null,
  company_name text null,
  phone text null,
  address text null,
  website text null,
  language_code text null,
  search_query text null,
  search_location text null,
  category text null,
  contact_person text null,
  email text null,
  designation text null,
  linkedin_url text null,
  whatsapp_number text null,
  products text null,
  lead_status text null,
  lead_source text null,
  notes text null,
  google_maps_url text null,
  country text null,
  city text null,
  "Type" text null,
  constraint contact_vendors_pkey primary key (id)
) TABLESPACE pg_default;

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.contact_vendors TO anon, authenticated;
GRANT ALL ON TABLE public.contact_vendors TO service_role;

NOTIFY pgrst, 'reload schema';
